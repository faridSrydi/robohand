export function useI18n() {
  const [lang, setLang] = useState(getLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.title = DICT[lang].docTitle;
  }, [lang]);

  useEffect(() => {
    const onExt = (e) => {
      if (e.detail === 'en' || e.detail === 'id') setLang(e.detail);
    };
    window.addEventListener(LANG_EVENT, onExt);
    return () => window.removeEventListener(LANG_EVENT, onExt);
  }, []);

  const toggleLang = () => setAppLang(lang === 'en' ? 'id' : 'en');
  return { lang, setLang: setAppLang, toggleLang, tr: DICT[lang] };
}
